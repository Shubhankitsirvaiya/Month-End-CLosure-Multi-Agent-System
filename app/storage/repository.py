"""Small JSON repository for runs, events, approvals, and evaluations.

The agent checkpoint is managed by LangGraph. This repository stores the
operator-facing projection so API restarts do not erase the audit trail.
"""
from __future__ import annotations

import json
from pathlib import Path
from threading import RLock
from typing import Any

from app.core.config import Settings, get_settings


class RunRepository:
    """Thread-safe, atomic JSON persistence for operator-facing run records.

    JSON is deliberately simple for teaching. The interface can later be backed
    by PostgreSQL or DynamoDB without changing orchestration code.
    """

    def __init__(self, settings: Settings | None = None) -> None:
        """Create the repository and ensure its root directory exists."""
        self.settings = settings or get_settings()
        self.root = self.settings.runtime_root / "runs"
        self.root.mkdir(parents=True, exist_ok=True)
        self._lock = RLock()

    def _path(self, run_id: str) -> Path:
        """Resolve a run ID to a safe local path and reject path traversal."""
        # Run IDs are generated by the API; this guard also prevents traversal.
        # Allow only the characters produced by our run-ID generator.
        safe = "".join(char for char in run_id if char.isalnum() or char in "-_")
        if safe != run_id:
            raise ValueError("Invalid run identifier")
        return self.root / f"{safe}.json"

    def save(self, run: dict[str, Any]) -> dict[str, Any]:
        """Atomically replace one run record.

        Writing a temporary file and renaming it prevents readers from observing
        half-written JSON if the process is interrupted during serialization.
        """
        with self._lock:
            path = self._path(run["run_id"])
            temporary = path.with_suffix(".tmp")
            # default=str handles timestamps/paths without losing the whole record.
            temporary.write_text(json.dumps(run, indent=2, default=str), encoding="utf-8")
            # Replace is atomic on the same filesystem.
            temporary.replace(path)
        return run

    def get(self, run_id: str) -> dict[str, Any] | None:
        """Load a run or return ``None`` when it does not exist."""
        path = self._path(run_id)
        if not path.exists():
            return None
        return json.loads(path.read_text(encoding="utf-8"))

    def list(self) -> list[dict[str, Any]]:
        """Return all runs newest first for the operations dashboard."""
        # Runtime root contains one JSON document per run; ignored by Git.
        records = [json.loads(path.read_text(encoding="utf-8")) for path in self.root.glob("*.json")]
        return sorted(records, key=lambda item: item.get("created_at", ""), reverse=True)

    def update(self, run_id: str, **changes: Any) -> dict[str, Any]:
        """Merge named fields into an existing record and persist it."""
        record = self.get(run_id)
        if record is None:
            raise KeyError(run_id)
        record.update(changes)
        return self.save(record)
